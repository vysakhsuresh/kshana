#!/usr/bin/env python3
"""Generate crates/kshana-frames/src/nutation/tables.rs from the ERFA sources.

ERFA (the BSD-licensed C port of SOFA) ships inside the pyerfa source distribution:
    pip download --no-deps --no-binary :all: pyerfa      # or fetch the sdist tarball
    tar xzf pyerfa-*.tar.gz
    python3 scripts/gen_nutation.py pyerfa-*/liberfa/erfa/src

The tables are the IAU 2000A luni-solar (678 terms) and planetary (687 terms) nutation
series and the IAU 2000B 77-term series, copied verbatim. Units: 0.1 µas.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(__file__).resolve().parent.parent / "crates/kshana-frames/src/nutation/tables.rs"


def rows(text, start_marker):
    i = text.index(start_marker)
    j = text.index("};", i)
    body = text[i:j]
    return [re.findall(r"-?\d+(?:\.\d+)?", m) for m in re.findall(r"\{([^{}]*)\}", body)]


a = (src / "nut00a.c").read_text()
b = (src / "nut00b.c").read_text()
xls = rows(a, "} xls[] = {")
xpl = rows(a, "} xpl[] = {")
xb = rows(b, "} x[] = {")
assert len(xls) == 678, len(xls)
assert len(xpl) == 687, len(xpl)
assert len(xb) == 77, len(xb)
for r in xls + xb:
    assert len(r) == 11, r
for r in xpl:
    assert len(r) == 17, r


def ls_row(r):
    ints = ", ".join(r[:5])
    fl = ", ".join(f"{float(x):.1f}" for x in r[5:])
    return f"    LsTerm {{ n: [{ints}], c: [{fl}] }},"


def pl_row(r):
    ints = ", ".join(r[:13])
    c = ", ".join(r[13:])
    return f"    PlTerm {{ n: [{ints}], c: [{c}] }},"


lines = [
    "//! IAU 2000A/B nutation coefficient tables, generated by `scripts/gen_nutation.py`",
    "//! from the ERFA sources (nut00a.c, nut00b.c). Do not edit by hand.",
    "//! Units of the coefficients: 0.1 microarcsecond (and the same per Julian century).",
    "",
    "/// Luni-solar term: multipliers of (l, l′, F, D, Ω) and coefficients",
    "/// (sp, spt, cp, ce, cet, se).",
    "pub struct LsTerm {",
    "    /// Multipliers of l, l′, F, D, Ω.",
    "    pub n: [i32; 5],",
    "    /// sin ψ, t·sin ψ, cos ψ, cos ε, t·cos ε, sin ε.",
    "    pub c: [f64; 6],",
    "}",
    "",
    "/// Planetary term: multipliers of (l, F, D, Ω, Me, Ve, E, Ma, Ju, Sa, Ur, Ne, pA) and",
    "/// integer coefficients (sp, cp, se, ce).",
    "pub struct PlTerm {",
    "    /// Multipliers of l, F, D, Ω, L_Me, L_Ve, L_E, L_Ma, L_Ju, L_Sa, L_Ur, L_Ne, p_A.",
    "    pub n: [i32; 13],",
    "    /// sin ψ, cos ψ, sin ε, cos ε.",
    "    pub c: [i32; 4],",
    "}",
    "",
    "/// IAU 2000A luni-solar series (678 terms).",
    "pub static LUNISOLAR_2000A: [LsTerm; 678] = [",
    *[ls_row(r) for r in xls],
    "];",
    "",
    "/// IAU 2000A planetary series (687 terms).",
    "pub static PLANETARY_2000A: [PlTerm; 687] = [",
    *[pl_row(r) for r in xpl],
    "];",
    "",
    "/// IAU 2000B luni-solar series (77 terms).",
    "pub static LUNISOLAR_2000B: [LsTerm; 77] = [",
    *[ls_row(r) for r in xb],
    "];",
    "",
]
# CIO locator s (IAU 2006) series from s06.c: terms {nfa[8], s, c} in arcsec.
s06 = (src / "s06.c").read_text()


def s06_rows(name):
    i = s06.index(f"{name}[] = {{")
    j = s06.index("};", i)
    body = s06[i:j]
    rows_ = []
    for m in re.finditer(r"\{\{([^}]*)\},\s*([-\d.e]+),\s*([-\d.e]+)\s*\}", body):
        nfa = [int(x) for x in m.group(1).split(",")]
        rows_.append((nfa, m.group(2), m.group(3)))
    return rows_


sp = re.findall(r"-?\d+\.\d+e-6", s06[s06.index("sp[] = {"):s06.index("};", s06.index("sp[] = {"))])
assert len(sp) == 6, sp
series = {n: s06_rows(n) for n in ("s0", "s1", "s2", "s3", "s4")}
assert [len(series[n]) for n in ("s0", "s1", "s2", "s3", "s4")] == [33, 3, 25, 4, 1], {n: len(v) for n, v in series.items()}
lines += [
    "/// CIO locator term: multipliers of (l, l′, F, D, Ω, L_Ve, L_E, p_A) and sin/cos",
    "/// coefficients in arcseconds.",
    "pub struct CioTerm {",
    "    /// Multipliers of the eight fundamental arguments.",
    "    pub nfa: [i32; 8],",
    "    /// Sine coefficient, arcsec.",
    "    pub s: f64,",
    "    /// Cosine coefficient, arcsec.",
    "    pub c: f64,",
    "}",
    "",
    "/// Polynomial coefficients of s (arcsec), powers 0–5 of t.",
    f"pub static CIO_POLY: [f64; 6] = [{', '.join(sp)}];",
    "",
]
for n, idx in (("s0", 0), ("s1", 1), ("s2", 2), ("s3", 3), ("s4", 4)):
    lines.append(f"/// CIO locator series, coefficient of t^{idx}.")
    lines.append(f"pub static CIO_S{idx}: [CioTerm; {len(series[n])}] = [")
    for nfa, sv, cv in series[n]:
        lines.append(f"    CioTerm {{ nfa: [{', '.join(str(x) for x in nfa)}], s: {sv}, c: {cv} }},")
    lines.append("];")
    lines.append("")
out.write_text("\n".join(lines))
print(f"wrote {out} ({len(xls)} + {len(xpl)} + {len(xb)} nutation terms, {sum(len(v) for v in series.values())} CIO terms)")
