/// A life's name inside a sentence: lower case in English.
pub fn life_lower(lang: Lang, life: Life) -> String {
    match lang {
        Lang::En => life.name().to_ascii_lowercase(),
        _ => life_name(lang, life).to_string(),
    }
}

