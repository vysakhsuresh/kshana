fn idx(l: DashaLord) -> usize {
    match l {
        DashaLord::Sun => 0,
        DashaLord::Moon => 1,
        DashaLord::Mars => 2,
        DashaLord::Mercury => 3,
        DashaLord::Jupiter => 4,
        DashaLord::Venus => 5,
        DashaLord::Saturn => 6,
        DashaLord::Rahu => 7,
        DashaLord::Ketu => 8,
    }
}

const MONTHS_EN_SHORT: [&str; 12] = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
const MONTHS_EN: [&str; 12] = [
    "January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December",
];
const MONTHS_ML: [&str; 12] = [
    "ജനുവരി", "ഫെബ്രുവരി", "മാർച്ച്", "ഏപ്രിൽ", "മേയ്", "ജൂൺ", "ജൂലൈ", "ഓഗസ്റ്റ്", "സെപ്റ്റംബർ", "ഒക്ടോബർ", "നവംബർ", "ഡിസംബർ",
];
const MONTHS_HI: [&str; 12] = [
    "जनवरी", "फ़रवरी", "मार्च", "अप्रैल", "मई", "जून", "जुलाई", "अगस्त", "सितंबर", "अक्टूबर", "नवंबर", "दिसंबर",
];

fn local(t: Instant, lon: f64) -> Utc {
    Utc::from_instant(t.add_ns((lon / 15.0 * 3_600.0 * NS_PER_SEC as f64) as i128))
}

/// A date in the reader's language: "23 Feb 2028", "2028 ഫെബ്രുവരി 23", "23 फ़रवरी 2028".
pub fn date(lang: Lang, t: Instant, lon: f64) -> String {
    let u = local(t, lon);
    let m = (u.month as usize).clamp(1, 12) - 1;
    match lang {
        Lang::En => format!("{} {} {}", u.day, MONTHS_EN_SHORT[m], u.year),
        Lang::Ml => format!("{} {} {}", u.year, MONTHS_ML[m], u.day),
        Lang::Hi => format!("{} {} {}", u.day, MONTHS_HI[m], u.year),
    }
}

/// A month and year: "June 2025", "2025 ജൂൺ", "जून 2025".
pub fn month_year(lang: Lang, t: Instant, lon: f64) -> String {
    let u = local(t, lon);
    let m = (u.month as usize).clamp(1, 12) - 1;
    match lang {
        Lang::En => format!("{} {}", MONTHS_EN[m], u.year),
        Lang::Ml => format!("{} {}", u.year, MONTHS_ML[m]),
        Lang::Hi => format!("{} {}", MONTHS_HI[m], u.year),
    }
}

/// "16:37" at the place's mean time.
pub fn hm(t: Instant, lon: f64) -> String {
    let u = local(t, lon);
    format!("{:02}:{:02}", u.hour, u.minute)
}

