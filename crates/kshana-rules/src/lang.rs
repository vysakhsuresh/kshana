/// What to do about a life's band, Malayalam or Hindi; `None` for English.
pub fn advice_sentence(lang: Lang, life: Life, band: Band) -> Option<&'static str> {
    let g = match band {
        Band::Bright | Band::Good => 0,
        Band::Steady => 1,
        Band::Slow | Band::Hold => 2,
    };
    match lang {
        Lang::En => None,
        Lang::Ml => Some(ADVICE_ML[life_idx(life)][g]),
        Lang::Hi => Some(ADVICE_HI[life_idx(life)][g]),
    }
}

