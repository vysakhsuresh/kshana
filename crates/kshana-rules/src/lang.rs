//! The plain vocabulary in Malayalam and Hindi, written for a common reader. English
//! stays the source (`crate::plain`); every function here takes a `Lang` and returns the
//! English from `plain` for `Lang::En`, so callers can use these everywhere.
//!
//! Care in Malayalam: suffixes join words, so the checker in `plain::jargon_in` matches
//! substrings. Words like ഗുരുതരം, സ്വഭാവം and ദശാബ്ദം would trip it and are avoided.

