/// A weekday by index, 0 = Sunday.
pub fn weekday(lang: Lang, d: usize) -> &'static str {
    lang.pick(WEEKDAY[d % 7])
}

/// "any day".
pub fn any_day(lang: Lang) -> &'static str {
    lang.pick(["any day", "ഏതു ദിവസവും", "कोई भी दिन"])
}

/// The weekday that belongs to an influence (its traditional day), 0 = Sunday.
pub fn day_of(l: DashaLord) -> usize {
    match l {
        DashaLord::Sun => 0,
        DashaLord::Moon => 1,
        DashaLord::Mars | DashaLord::Ketu => 2,
        DashaLord::Mercury => 3,
        DashaLord::Jupiter => 4,
        DashaLord::Venus => 5,
        DashaLord::Saturn | DashaLord::Rahu => 6,
    }
}

/// The weekday of a ruling lord (the day lord), 0 = Sunday.
pub fn weekday_of_lord(l: DashaLord) -> Option<usize> {
    match l {
        DashaLord::Sun => Some(0),
        DashaLord::Moon => Some(1),
        DashaLord::Mars => Some(2),
        DashaLord::Mercury => Some(3),
        DashaLord::Jupiter => Some(4),
        DashaLord::Venus => Some(5),
        DashaLord::Saturn => Some(6),
        _ => None,
    }
}

