/// The Malayalam and Hindi rows for a key.
pub(crate) fn text(key: &str) -> Option<(&'static YogaText, &'static YogaText)> {
    TEXT.iter().find(|r| r.0 == key).map(|r| (&r.1, &r.2))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::plain::{jargon_in, Lang};
    use crate::yogas::CATALOG;

    #[test]
    fn every_yoga_has_both_languages_and_nothing_extra() {
        for d in CATALOG {
            assert!(text(d.key).is_some(), "no ml/hi row for {}", d.key);
        }
        for (k, _, _) in TEXT {
            assert!(CATALOG.iter().any(|d| d.key == *k), "extra row {k}");
        }
        let mut ks: Vec<&str> = TEXT.iter().map(|r| r.0).collect();
        ks.sort_unstable();
        let n = ks.len();
        ks.dedup();
        assert_eq!(ks.len(), n, "duplicate rows");
    }

    #[test]
    fn rows_are_plain_where_plain_and_in_script() {
        for d in CATALOG {
            let (ml, hi) = text(d.key).unwrap();
            for (lang, t) in [(Lang::Ml, ml), (Lang::Hi, hi)] {
                assert_eq!(t.care.is_empty(), d.care.is_empty(), "{} {:?}: care", d.key, lang);
                for (field, s) in [("title", t.title), ("meaning", t.meaning), ("care", t.care)] {
                    assert_eq!(jargon_in(lang, s), None, "{} {:?}.{field}: {s}", d.key, lang);
                }
                for (field, s) in [("name", t.name), ("source", t.source), ("rule", t.rule), ("title", t.title), ("meaning", t.meaning), ("care", t.care)] {
                    assert!(!s.chars().any(|c| c.is_ascii_alphabetic()), "{} {:?}.{field} has Latin: {s}", d.key, lang);
                    if field != "care" {
                        assert!(!s.is_empty(), "{} {:?}.{field} empty", d.key, lang);
                    }
                }
            }
        }
    }

    #[test]
    fn accessors_pick_the_language() {
        let d = crate::yogas::def("gaja_kesari");
        assert_eq!(d.name_in(Lang::En), "Gaja Kesari");
        assert_eq!(d.name_in(Lang::Ml), "ഗജകേസരി യോഗം");
        assert_eq!(d.name_in(Lang::Hi), "गजकेसरी योग");
        assert_eq!(d.title_in(Lang::En), d.title);
    }
}
